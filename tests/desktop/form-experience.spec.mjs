import { clickControl, revealControl, moreAction } from '../helpers/ui-actions.mjs'
import { test, expect } from '../helpers/desktop-application.mjs'

test('research forms support collecting first, optional details and preserved evidence in desktop and narrow layouts', async ({ desktop }, testInfo) => {
  const { page } = desktop, errors = []
  page.on('pageerror', error => errors.push(error.message))
  const capture = async name => {
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath(name + '.png') })
  }
  const cancel = id => page.locator('#' + id).getByRole('button', { name: '取消', exact: true }).click()
  const request = (path, body, method = 'PATCH') => page.evaluate(async ({ path, body, method }) => {
    const response = await fetch(path, body === undefined ? {} : { method, headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) })
    const value = await response.json(); if (!response.ok) throw new Error(value.error); return value
  }, { path, body, method })

  await page.locator('#new-topic').click()
  await expect(page.locator('#topic-question-input')).not.toBeVisible()
  await page.locator('#topic-name-input').fill('城市绿地与居民健康')
  await capture('topic-desktop')
  await page.setViewportSize({ width: 390, height: 844 })
  await capture('topic-narrow')
  await page.locator('#topic-form button[type="submit"]').click()
  await expect(page.locator('#topic-dialog')).not.toBeVisible()
  await expect(page.locator('#topic-title')).toHaveText('城市绿地与居民健康')
  await expect(page.locator('#topic-description')).not.toBeVisible()
  await page.setViewportSize({ width: 1280, height: 900 })
  const topic = (await request('/api/topics')).topics[0]
  expect(topic.question).toBe('')

  const docs = await page.evaluate(async topicId => {
    const docs = []
    for (const [title, text] of [['城市公园与居民步行', '研究观察居民步行频率，比较公园距离与活动时间。'], ['绿地可达性与心理健康', '研究通过问卷评价心理健康，关注绿地可达性。']]) {
      const form = new FormData(); form.append('file', new Blob(['# ' + title + '\n\n' + text]), title + '.md'); form.append('topicId', topicId)
      const response = await fetch('/api/documents', { method: 'POST', body: form })
      if (!response.ok) throw new Error(await response.text()); docs.push(await response.json())
    }
    return docs
  }, topic.id)
  await page.reload()
  await expect(page.locator('#topic-documents .document-card')).toHaveCount(2)
  const card = () => page.locator(`#topic-documents .document-card[data-document-id="${docs[0].id}"]`)
  await card().getByRole('button', { name: '筛选与阅读记录', exact: true }).click()
  await expect(page.locator('#record-reason')).not.toBeVisible()
  await page.locator('#record-selection').selectOption('included')
  await capture('record-desktop')
  await page.setViewportSize({ width: 390, height: 844 }); await capture('record-narrow')
  await page.locator('#record-form button[type="submit"]').click()
  await expect(page.locator('#record-dialog')).not.toBeVisible()
  await expect(card()).toContainText('已纳入')
  await page.setViewportSize({ width: 1280, height: 900 })

  // Existing explanatory fields stay separate and survive a status-only edit.
  await request(`/api/topics/${topic.id}/documents/${docs[0].id}`, { reason: '方法符合纳入范围', relevance: '帮助比较步行活动的测量方式' })
  await request(`/api/documents/${docs[0].id}`, { venue: '城市健康研究', doi: '10.1234/green', url: 'https://example.org/green' })
  await page.reload()
  await card().getByRole('button', { name: '筛选与阅读记录', exact: true }).click()
  await expect(page.locator('#record-reason')).toHaveValue('方法符合纳入范围')
  await expect(page.locator('#record-relevance')).toHaveValue('帮助比较步行活动的测量方式')
  await page.locator('#record-reading').selectOption('reading')
  await page.locator('#record-form button[type="submit"]').click()
  const retained = (await request('/api/topics/' + topic.id)).documents.find(link => link.documentId === docs[0].id)
  expect(retained.reason).toBe('方法符合纳入范围'); expect(retained.relevance).toBe('帮助比较步行活动的测量方式')

  await moreAction(card(), '书目信息')
  await expect(page.locator('#metadata-details-summary')).toContainText('已填写')
  await expect(page.locator('#metadata-doi')).not.toBeVisible()
  await capture('metadata-desktop')
  await page.setViewportSize({ width: 390, height: 844 }); await capture('metadata-narrow')
  await page.locator('#metadata-authors').fill('研究小组')
  await page.locator('#metadata-form button[type="submit"]').click()
  const bibliography = (await request('/api/documents/' + docs[0].id)).bibliography
  expect(bibliography).toMatchObject({ authors: '研究小组', venue: '城市健康研究', doi: '10.1234/green', url: 'https://example.org/green' })
  await page.setViewportSize({ width: 1280, height: 900 })
  // Native validation reveals invalid fields even after their section was closed.
  await moreAction(card(), '书目信息')
  await page.locator('#metadata-details > summary').click()
  await page.locator('#metadata-url').fill('invalid-url')
  await page.locator('#metadata-details > summary').click()
  await page.locator('#metadata-form button[type="submit"]').click()
  await expect(page.locator('#metadata-url')).toBeVisible()
  await page.locator('#metadata-url').fill('https://example.org/green')
  await cancel('metadata-dialog')

  await page.locator('#new-comparison').click()
  await expect(page.locator('#cmp-question')).toHaveValue('')
  await expect(page.locator('.comparison-document-options input:checked')).toHaveCount(2)
  await page.locator('#cmp-question').fill('不同研究如何衡量绿地对健康的影响？')
  while (await page.locator('.comparison-column-option').count() > 1) await page.locator('.comparison-column-option').last().getByRole('button', { name: '移除维度' }).click()
  await page.locator('.column-name').fill('研究方法')
  await capture('comparison-config-desktop')
  await page.setViewportSize({ width: 390, height: 844 }); await capture('comparison-config-narrow')
  await page.locator('#comparison-save').click()
  await expect(page.locator('#comparison-editor')).not.toBeVisible()
  await page.setViewportSize({ width: 1280, height: 900 })
  const row = () => page.locator(`#comparison-grid tr[data-document-id="${docs[0].id}"]`)
  await row().getByRole('button', { name: '编辑比较项', exact: true }).click()
  await expect(page.locator('#cmp-conditions')).not.toBeVisible()
  await expect(page.locator('#cmp-reason')).not.toBeVisible()
  await page.locator('#cmp-value').fill('通过观察记录居民步行频率。')
  await expect(page.locator('#cmp-status')).toHaveValue('recorded')
  await capture('comparison-cell-desktop')
  await page.setViewportSize({ width: 390, height: 844 }); await capture('comparison-cell-narrow')
  await page.locator('#cmp-comparability').selectOption('conditional')
  await expect(page.locator('#cmp-reason')).toBeVisible()
  await page.locator('#comparison-save').click()
  await expect(page.locator('#comparison-editor-error')).toContainText('原因')
  await page.locator('#cmp-reason').fill('需要统一观察时长')
  await page.locator('#cmp-details > summary').click()
  await page.locator('#cmp-conditions').fill('社区步行观察')
  await page.locator('#cmp-kind').selectOption('source')
  await page.locator('#cmp-sources > summary').click()
  await page.getByRole('button', { name: '选择当前原文', exact: true }).click()
  await page.locator('.comparison-reference-options input[type="checkbox"]').first().check()
  await page.locator('#comparison-save').click()
  await expect(page.locator('#comparison-editor')).not.toBeVisible()
  await expect(row()).toContainText('有条件可比')
  await page.reload()
  await row().getByRole('button', { name: '编辑比较项', exact: true }).click()
  await expect(page.locator('#cmp-value')).toHaveValue('通过观察记录居民步行频率。')
  await expect(page.locator('#cmp-conditions')).toHaveValue('社区步行观察')
  await expect(page.locator('#cmp-reason')).toHaveValue('需要统一观察时长')
  await expect(page.locator('.note-evidence .comparison-citation')).toHaveCount(1)
  await cancel('comparison-editor')

  await page.setViewportSize({ width: 1280, height: 900 })
  await page.locator('#model-settings-open').click(); await capture('model-desktop')
  await page.setViewportSize({ width: 390, height: 844 }); await capture('model-narrow')
  await cancel('model-settings-dialog')
  await expect(page.locator('#model-settings-dialog')).not.toBeVisible()
  expect(errors).toEqual([])
})
