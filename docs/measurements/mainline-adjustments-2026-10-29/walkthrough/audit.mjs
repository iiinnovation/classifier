async function shot(page, name) {
  await page.evaluate(() => window.scrollTo(0, 0))
  const state = await page.evaluate(() => {
    const visible = el => el.checkVisibility() && !el.closest('details:not([open]) :not(summary)')
    const buttons = [...document.querySelectorAll('button')].filter(visible).map(el => ({ text: el.textContent.trim(), disabled: el.disabled, y: Math.round(el.getBoundingClientRect().top + scrollY) }))
    const sections = [...document.querySelectorAll('main h1, main h2, main h3')].filter(visible).map(el => ({ text: el.textContent.trim(), y: Math.round(el.getBoundingClientRect().top + scrollY) }))
    return { width: innerWidth, height: innerHeight, documentHeight: document.documentElement.scrollHeight, overflow: document.documentElement.scrollWidth > innerWidth, buttons, sections, text: document.body.innerText }
  })
  snapshots.push({ name, ...state })
  await page.screenshot({ path: out + '/' + name + '.png', fullPage: true })
}
